CREATE TABLE `BookIndexExternalBook` (
  `id` CHAR(36) NOT NULL,
  `sourceId` CHAR(36) NOT NULL,
  `sourceKey` VARCHAR(255) NOT NULL,
  `sourceExternalId` VARCHAR(180) NULL,
  `title` VARCHAR(300) NOT NULL,
  `normalizedTitle` VARCHAR(300) NOT NULL,
  `authorName` VARCHAR(220) NULL,
  `normalizedAuthor` VARCHAR(220) NULL,
  `publisherName` VARCHAR(220) NULL,
  `isbn13` CHAR(13) NULL,
  `isbn10` CHAR(10) NULL,
  `productUrl` VARCHAR(1200) NOT NULL,
  `imageUrl` VARCHAR(1200) NULL,
  `masterBookId` CHAR(36) NULL,
  `matchStatus` ENUM('unmatched','auto_matched','manual_matched','rejected') NOT NULL DEFAULT 'unmatched',
  `matchConfidence` DOUBLE NULL,
  `firstSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `lastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `BookIndexExternalBook_sourceId_sourceKey_key`(`sourceId`, `sourceKey`),
  INDEX `BookIndexExternalBook_sourceId_matchStatus_lastSeenAt_idx`(`sourceId`, `matchStatus`, `lastSeenAt`),
  INDEX `BookIndexExternalBook_masterBookId_lastSeenAt_idx`(`masterBookId`, `lastSeenAt`),
  INDEX `BookIndexExternalBook_isbn13_idx`(`isbn13`),
  INDEX `BookIndexExternalBook_normalizedTitle_normalizedAuthor_idx`(`normalizedTitle`, `normalizedAuthor`),
  PRIMARY KEY (`id`),
  CONSTRAINT `BookIndexExternalBook_sourceId_fkey` FOREIGN KEY (`sourceId`) REFERENCES `BookIndexSource`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `BookIndexExternalBook_masterBookId_fkey` FOREIGN KEY (`masterBookId`) REFERENCES `BookIndexBook`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `BookIndexFetchRun` (
  `id` CHAR(36) NOT NULL,
  `listId` CHAR(36) NOT NULL,
  `status` ENUM('running','success','no_change','partial','failed') NOT NULL DEFAULT 'running',
  `startedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completedAt` DATETIME(3) NULL,
  `itemsFound` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `itemsStored` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `fingerprint` CHAR(64) NULL,
  `errorCode` VARCHAR(80) NULL,
  `errorMessage` VARCHAR(1000) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `BookIndexFetchRun_listId_startedAt_idx`(`listId`, `startedAt`),
  INDEX `BookIndexFetchRun_status_startedAt_idx`(`status`, `startedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `BookIndexFetchRun_listId_fkey` FOREIGN KEY (`listId`) REFERENCES `BookIndexList`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `BookIndexObservation` (
  `id` CHAR(36) NOT NULL,

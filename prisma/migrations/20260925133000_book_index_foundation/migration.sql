CREATE TABLE `BookIndexSource` (
  `id` CHAR(36) NOT NULL,
  `code` VARCHAR(40) NOT NULL,
  `name` VARCHAR(120) NOT NULL,
  `marketCode` VARCHAR(16) NOT NULL,
  `countryCode` CHAR(2) NOT NULL,
  `baseUrl` VARCHAR(500) NOT NULL,
  `includeInTurkeyIndex` BOOLEAN NOT NULL DEFAULT false,
  `status` ENUM('active','paused','blocked') NOT NULL DEFAULT 'active',
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `BookIndexSource_code_key`(`code`),
  INDEX `BookIndexSource_marketCode_status_idx`(`marketCode`, `status`),
  INDEX `BookIndexSource_includeInTurkeyIndex_status_idx`(`includeInTurkeyIndex`, `status`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `BookIndexList` (
  `id` CHAR(36) NOT NULL,
  `sourceId` CHAR(36) NOT NULL,
  `code` VARCHAR(80) NOT NULL,
  `title` VARCHAR(180) NOT NULL,
  `categoryKey` VARCHAR(120) NOT NULL DEFAULT 'general',
  `period` ENUM('live','daily','weekly','monthly','yearly') NOT NULL,
  `sourceUrl` VARCHAR(1000) NOT NULL,
  `maxRank` SMALLINT UNSIGNED NULL,
  `includeInComposite` BOOLEAN NOT NULL DEFAULT false,
  `collectionEveryMinutes` SMALLINT UNSIGNED NULL,
  `active` BOOLEAN NOT NULL DEFAULT true,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `BookIndexList_sourceId_code_key`(`sourceId`, `code`),
  INDEX `BookIndexList_sourceId_active_period_idx`(`sourceId`, `active`, `period`),
  INDEX `BookIndexList_categoryKey_period_active_idx`(`categoryKey`, `period`, `active`),
  INDEX `BookIndexList_includeInComposite_active_idx`(`includeInComposite`, `active`),
  PRIMARY KEY (`id`),
  CONSTRAINT `BookIndexList_sourceId_fkey` FOREIGN KEY (`sourceId`) REFERENCES `BookIndexSource`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;


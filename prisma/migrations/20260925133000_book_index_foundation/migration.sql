  INDEX `BookIndexObservation_externalBookId_observedAt_idx`(`externalBookId`, `observedAt`),
  INDEX `BookIndexObservation_observedAt_idx`(`observedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `BookIndexObservation_fetchRunId_fkey` FOREIGN KEY (`fetchRunId`) REFERENCES `BookIndexFetchRun`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `BookIndexObservation_externalBookId_fkey` FOREIGN KEY (`externalBookId`) REFERENCES `BookIndexExternalBook`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

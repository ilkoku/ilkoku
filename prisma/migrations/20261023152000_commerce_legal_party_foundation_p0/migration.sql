-- Additive P0-01/02/03 foundation only. Never backfill authorId as seller.
-- No payment activation, no changes to historic orders/entitlements.

CREATE TABLE `LegalParty` (
  `id` CHAR(36) NOT NULL,
  `kind` ENUM('platform','individual','organization') NOT NULL,
  `ownerUserId` CHAR(36) NULL,
  `publisherId` CHAR(36) NULL,
  `legalName` VARCHAR(240) NULL,
  `tradeName` VARCHAR(240) NULL,
  `taxIdentifier` VARCHAR(32) NULL,
  `taxOffice` VARCHAR(160) NULL,
  `registryNumber` VARCHAR(64) NULL,
  `legalAddress` TEXT NULL,
  `contactEmail` VARCHAR(320) NULL,
  `contactPhone` VARCHAR(32) NULL,
  `countryCode` CHAR(2) NOT NULL DEFAULT 'TR',
  `verificationStatus` ENUM('pending','verified','rejected','suspended') NOT NULL DEFAULT 'pending',
  `verifiedById` CHAR(36) NULL,
  `verifiedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX `LegalParty_kind_verificationStatus_idx` (`kind`, `verificationStatus`),
  INDEX `LegalParty_ownerUserId_verificationStatus_idx` (`ownerUserId`, `verificationStatus`),
  INDEX `LegalParty_publisherId_verificationStatus_idx` (`publisherId`, `verificationStatus`),
  INDEX `LegalParty_verifiedById_fkey` (`verifiedById`),
  PRIMARY KEY (`id`),
  CONSTRAINT `LegalParty_ownerUserId_fkey` FOREIGN KEY (`ownerUserId`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `LegalParty_publisherId_fkey` FOREIGN KEY (`publisherId`) REFERENCES `Publisher`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `LegalParty_verifiedById_fkey` FOREIGN KEY (`verifiedById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `WorkSalesAuthorization` (
  `id` CHAR(36) NOT NULL,
  `workId` CHAR(36) NOT NULL,
  `legalPartyId` CHAR(36) NOT NULL,
  `version` INTEGER UNSIGNED NOT NULL DEFAULT 1,
  `status` ENUM('pending','verified','rejected','revoked','expired') NOT NULL DEFAULT 'pending',
  `rightsScope` JSON NULL,
  `documentHash` CHAR(64) NULL,
  `validFrom` DATETIME(3) NULL,
  `validUntil` DATETIME(3) NULL,
  `verifiedById` CHAR(36) NULL,
  `verifiedAt` DATETIME(3) NULL,
  `revokedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `WorkSalesAuthorization_workId_legalPartyId_version_key` (`workId`, `legalPartyId`, `version`),
  INDEX `WorkSalesAuthorization_legalPartyId_status_idx` (`legalPartyId`, `status`),
  INDEX `WorkSalesAuthorization_workId_status_validUntil_idx` (`workId`, `status`, `validUntil`),
  INDEX `WorkSalesAuthorization_verifiedById_fkey` (`verifiedById`),
  PRIMARY KEY (`id`),
  CONSTRAINT `WorkSalesAuthorization_workId_fkey` FOREIGN KEY (`workId`) REFERENCES `Work`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `WorkSalesAuthorization_legalPartyId_fkey` FOREIGN KEY (`legalPartyId`) REFERENCES `LegalParty`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `WorkSalesAuthorization_verifiedById_fkey` FOREIGN KEY (`verifiedById`) REFERENCES `User`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `WorkSellerAssignment` (
  `id` CHAR(36) NOT NULL,

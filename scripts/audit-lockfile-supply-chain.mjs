import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCKFILE = path.join(ROOT, "package-lock.json");
const OUTPUT = path.join(ROOT, "src", "features", "system-map", "supply-chain.generated.ts");

const advisoryPolicy = {
  packageName: "brace-expansion",
  advisories: ["CVE-2026-14257", "CVE-2026-69152"],
  patchedLines: ["1.1.18", "2.1.4", "3.0.6", "5.0.9"],
  note: "CVE-2026-14257 bazı tarayıcılarda düz <=5.0.7 aralığıyla raporlanabilir; 1.x/2.x/3.x backportları ve sonraki CVE-2026-69152 için hat bazlı yamalı eşikler uygulanır.",
};

function parseVersion(value) {
  const match = /^(\d+)\.(\d+)\.(\d+)/u.exec(String(value ?? ""));
  return match ? match.slice(1, 4).map(Number) : null;
}

function compare(left, right) {
  for (let index = 0; index < 3; index += 1) {
    if (left[index] !== right[index]) return left[index] - right[index];
  }
  return 0;
}

function isPatchedBraceExpansion(version) {
  const parsed = parseVersion(version);
  if (!parsed) return false;
  const [major] = parsed;
  if (major === 1) return compare(parsed, [1, 1, 18]) >= 0;
  if (major === 2) return compare(parsed, [2, 1, 4]) >= 0;
  if (major === 3) return compare(parsed, [3, 0, 6]) >= 0;
  if (major === 4) return false;
  if (major >= 5) return compare(parsed, [5, 0, 9]) >= 0;
  return false;
}

function packageNameFromPath(packagePath) {
  const segments = packagePath.split("/node_modules/");
  return segments.at(-1)?.replace(/^node_modules\//u, "") ?? packagePath;
}

function directParents(packages, dependencyName) {
  return Object.entries(packages)
    .filter(([, metadata]) => metadata?.dependencies?.[dependencyName])
    .map(([packagePath, metadata]) => ({
      package: packageNameFromPath(packagePath),
      packagePath: packagePath || "<root>",
      version: metadata.version ?? null,
      requestedRange: metadata.dependencies[dependencyName],
      scope: metadata.dev === true ? "development" : "runtime",
    }))
    .sort((left, right) => left.packagePath.localeCompare(right.packagePath));
}

const lock = JSON.parse(await readFile(LOCKFILE, "utf8"));
const packages = lock.packages ?? {};
const instances = Object.entries(packages)
  .filter(([packagePath]) => packagePath === "node_modules/brace-expansion" || packagePath.endsWith("/node_modules/brace-expansion"))
  .map(([packagePath, metadata]) => {
    const patched = isPatchedBraceExpansion(metadata.version);
    return {
      packagePath,
      version: metadata.version ?? "unknown",
      scope: metadata.dev === true ? "development" : "runtime",
      patched,
      status: patched ? "pass" : "blocker",
    };
  })
  .sort((left, right) => left.packagePath.localeCompare(right.packagePath));

if (instances.length === 0) {
  console.error("Supply-chain audit failed: brace-expansion instance was not found in package-lock.json.");
  process.exit(1);
}

const blockers = instances.filter((instance) => !instance.patched);
const report = {
  generatedAt: new Date().toISOString(),
  source: "package-lock.json",
  policy: advisoryPolicy,
  summary: {
    instances: instances.length,
    blockers: blockers.length,
    runtimeInstances: instances.filter((instance) => instance.scope === "runtime").length,
    developmentInstances: instances.filter((instance) => instance.scope === "development").length,
  },
  instances,
  directParents: directParents(packages, advisoryPolicy.packageName),
  scannerDiscrepancy: {
    package: "brace-expansion@1.1.18",
    classification: "patched-development-instance",
    detail: "Hostinger gibi CVE-2026-14257 için düz <=5.0.7 aralığı kullanan tarayıcılar 1.1.18'i yanlış pozitif işaretleyebilir. Bu kapı hat bazlı yamalı eşikleri ve sonraki CVE-2026-69152 düzeltmesini birlikte uygular.",
  },
};

await writeFile(
  OUTPUT,
  `// Generated by scripts/audit-lockfile-supply-chain.mjs. Do not edit.\nexport const supplyChainSecurityReport = ${JSON.stringify(report, null, 2)} as const;\n`,
  "utf8",
);

for (const instance of instances) {
  console.log(`Supply-chain ${instance.status.toUpperCase()}: brace-expansion@${instance.version} · ${instance.scope} · ${instance.packagePath}`);
}

if (blockers.length > 0) {
  console.error("Supply-chain audit blocked: unpatched brace-expansion instance detected.");
  process.exit(1);
}

console.log(`Supply-chain audit passed: ${instances.length} brace-expansion instance(s), 0 blockers.`);
